export function useNavigation() {
  const route = useRoute()

  // Define navigation menu items
  const navigationItems = [
    { name: 'Dashboard', path: '/dashboard', icon: HomeIcon },
    { name: 'Company Information', path: '/company-info', icon: BuildingIcon },
    { name: 'Banner', path: '/banner', icon: ImageIcon },
    { name: 'About Company', path: '/about-company', icon: BuildingIcon },
    { name: 'Quote Price', path: '/quote-price', icon: DollarIcon },
    { name: 'Contact Info', path: '/contact-info', icon: PhoneIcon },
    { name: 'Base Info', path: '/base-info', icon: InfoIcon },
    { name: 'Settings', path: '/settings', icon: CogIcon }
  ]

  // Get navigation with current state
  const navigation = ref(
    navigationItems.map(item => ({
      ...item,
      current: route.path.startsWith(item.path) && item.path !== '/'
    }))
  )

  // Get navigation link for an item
  const getNavigationLink = (name) => {
    const item = navigationItems.find(nav => nav.name === name)
    return item ? item.path : '#'
  }

  // Update navigation current state
  const updateNavigation = () => {
    navigation.value = navigationItems.map(item => ({
      ...item,
      current: route.path.startsWith(item.path) && item.path !== '/'
    }))
  }

  return {
    navigation,
    navigationItems,
    getNavigationLink,
    updateNavigation
  }
}